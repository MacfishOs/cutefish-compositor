#include <gtest/gtest.h>
#include <tuple>
#include "display/display_layout.h"

using namespace cutefish::display;
namespace base = cutefish::base;

class TwoDisplays : public testing::TestWithParam<
    std::tuple<base::Rect, base::Rect, LayoutEdge, int, int, base::Rect, base::Rect>> {};

TEST_P(TwoDisplays, Placement)
{
    const auto& [primary, secondary, edge, offset, overlap, expectedPrimary, expectedSecondary] = GetParam();
    const DisplayId a("primary"), b("secondary");
    const auto result = DisplayLayout::resolve(a, {{a, primary.size()}, {b, secondary.size()}},
                                               {{b, a, edge, offset}}, overlap);
    ASSERT_TRUE(result.succeeded) << result.error.message;
    EXPECT_EQ(result.bounds.at(a), expectedPrimary);
    EXPECT_EQ(result.bounds.at(b), expectedSecondary);
}

